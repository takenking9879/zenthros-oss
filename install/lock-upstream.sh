# Pin every upstream download the installer makes: writes install/upstream.lock
# with one row per (key, arch): the URL and its SHA-256.
#
#   bash install/lock-upstream.sh            # rewrite install/upstream.lock
#
# Versions come from install/upstream.versions. The SHA-256 comes from the
# vendor's own checksum when it publishes one (Node SHASUMS256, the Go
# download index, uv's .sha256, the Adoptium API, containerd's .sha256sum);
# otherwise the file is downloaded and hashed here, once, at lock time.
# upstream.lock ships next to install-agent.sh and is listed in SHA256SUMS,
# so a pinned bootstrap pins every upstream file through one digest.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
VERSIONS="${HERE}/upstream.versions"
LOCK="${UPSTREAM_LOCK:-${HERE}/upstream.lock}"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

version() { awk -v k="$1" '$1 == k { print $2 }' "${VERSIONS}"; }
fetch() { curl -fsSL --retry 3 --retry-delay 2 "$@"; }
hash_url() { fetch -o "${WORK}/blob" "$1"; sha256sum "${WORK}/blob" | cut -d' ' -f1; }
row() { printf '%-32s %-6s %s %s\n' "$1" "$2" "$3" "$4"; }

ts="$(version tailscale)"
kr="$(version tailscale-keyring)"
uv="$(version uv)"
node="$(version node)"
go="$(version go)"
java="$(version java)"
ctd="$(version containerd)"
runc="$(version runc)"

{
  echo "# Generated by install/lock-upstream.sh from install/upstream.versions. Do not edit."
  echo "# key                            arch   sha256 url"
  for arch in amd64 arm64; do
    url="https://pkgs.tailscale.com/stable/ubuntu/pool/tailscale_${ts}_${arch}.deb"
    row "tailscale-deb@${ts}" "${arch}" "$(hash_url "${url}")" "${url}"
  done
  url="https://pkgs.tailscale.com/stable/ubuntu/pool/tailscale-archive-keyring_${kr}_all.deb"
  row "tailscale-keyring-deb@${kr}" all "$(hash_url "${url}")" "${url}"
  for pair in amd64:x86_64 arm64:aarch64; do
    arch="${pair%%:*}" rpm="${pair#*:}"
    url="https://pkgs.tailscale.com/stable/amazon-linux/2023/${rpm}/tailscale_${ts}_${rpm}.rpm"
    row "tailscale-rpm@${ts}" "${arch}" "$(hash_url "${url}")" "${url}"
  done

  # The static (musl) build: the same file runs on the host and, bound into
  # a container job, in an image of any libc (Alpine's musl among them).
  for pair in amd64:x86_64 arm64:aarch64; do
    arch="${pair%%:*}" triple="${pair#*:}-unknown-linux-musl"
    url="https://github.com/astral-sh/uv/releases/download/${uv}/uv-${triple}.tar.gz"
    row "uv@${uv}" "${arch}" "$(fetch "${url}.sha256" | cut -d' ' -f1)" "${url}"
  done

  fetch -o "${WORK}/node-sums" "https://nodejs.org/dist/v${node}/SHASUMS256.txt"
  for pair in amd64:x64 arm64:arm64; do
    arch="${pair%%:*}" file="node-v${node}-linux-${pair#*:}.tar.gz"
    row "node@${node}" "${arch}" "$(awk -v f="${file}" '$2 == f { print $1 }' "${WORK}/node-sums")" "https://nodejs.org/dist/v${node}/${file}"
  done

  fetch -o "${WORK}/go.json" "https://go.dev/dl/?mode=json&include=all"
  for arch in amd64 arm64; do
    file="go${go}.linux-${arch}.tar.gz"
    sum="$(python3 -c 'import json,sys
for r in json.load(open(sys.argv[1])):
    for f in r["files"]:
        if f["filename"] == sys.argv[2]: print(f["sha256"]); raise SystemExit' "${WORK}/go.json" "${file}")"
    row "go@${go}" "${arch}" "${sum}" "https://go.dev/dl/${file}"
  done

  for pair in amd64:x64 arm64:aarch64; do
    arch="${pair%%:*}"
    fetch -o "${WORK}/java.json" "https://api.adoptium.net/v3/assets/release_name/eclipse/jdk-${java}?architecture=${pair#*:}&image_type=jdk&os=linux&vendor=eclipse"
    read -r sum url < <(python3 -c 'import json,sys
d=json.load(open(sys.argv[1]))
for b in d["binaries"]:
    if b["image_type"] == "jdk" and b["os"] == "linux":
        print(b["package"]["checksum"], b["package"]["link"]); break' "${WORK}/java.json")
    row "java@${java}" "${arch}" "${sum}" "${url}"
  done

  for arch in amd64 arm64; do
    url="https://github.com/containerd/containerd/releases/download/v${ctd}/containerd-${ctd}-linux-${arch}.tar.gz"
    row "containerd@${ctd}" "${arch}" "$(fetch "${url}.sha256sum" | cut -d' ' -f1)" "${url}"
    url="https://github.com/opencontainers/runc/releases/download/v${runc}/runc.${arch}"
    row "runc@${runc}" "${arch}" "$(fetch "https://github.com/opencontainers/runc/releases/download/v${runc}/runc.sha256sum" | awk -v f="runc.${arch}" '$2 == f || $2 == "*"f { print $1 }')" "${url}"
  done
} > "${LOCK}.next"

if awk '!/^#/ && (NF != 4 || length($3) != 64) { bad = 1; print "bad row: " $0 > "/dev/stderr" } END { exit bad }' "${LOCK}.next"; then
  mv "${LOCK}.next" "${LOCK}"
  echo "wrote ${LOCK}"
else
  rm -f "${LOCK}.next"
  echo "lock-upstream.sh: a row is missing its SHA-256; nothing written" >&2
  exit 1
fi
