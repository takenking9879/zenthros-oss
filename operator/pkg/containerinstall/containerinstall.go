// Package containerinstall is install-container.sh: what attaches a
// container that is already running, as install-agent.sh does a VM. A
// person runs `curl -fsSL <base>/install-container.sh | sh`, with no secrets
// and no flags: the installer is published with the agent (install/stage.sh
// runs `zenadm container-installer` and writes in where it publishes it). It
// downloads the agent from there, checks it against the SHA256SUMS there, as
// a Managed container does (containerboot.Fetch), and writes a zenadm that
// knows one command, pinned to that SHA256SUMS. Then the one-time `zenadm
// join`, with zenadm join's flags: that zenadm verifies the agent again and
// runs `zenthros-agent attach`, which takes the token and the tailnet key out
// of its arguments before any job can read them.
package containerinstall

import (
	"fmt"
	"strings"

	"github.com/zenthros/operator/pkg/containerboot"
	"github.com/zenthros/operator/pkg/infrastructure/provider/containerhosts"
)

// Name is install-container.sh's name next to the agent.
const Name = "install-container.sh"

// containerZenadmMark is the line that says a zenadm is the one
// install-container.sh writes, which it may replace.
const containerZenadmMark = "# zenadm-container"

// installerHead takes the installer's flags, all optional. The join's are
// refused: they go to zenadm join. %s is where it is published.
const installerHead = `#!/bin/sh
# install-container.sh: installs the Zenthros agent in the container it runs
# in, as install-agent.sh does on a VM. No secrets, no join and no flags:
#
#   curl -fsSL <where it is published>/install-container.sh | sh
#
# then paste the one-time zenadm join command that zenadm token create
# --attach prints. Generated by zenadm container-installer.
#
# It downloads the agent from where it is published and checks it against
# the SHA256SUMS there, which the zenadm it writes keeps pinned. Optional
# flags: --install-base (another directory), --artifact-urls "name=url ..."
# (each file's own URL, presigned), --sha256sums (the SHA-256 that
# SHA256SUMS must have), --bin-dir (or ZENTHROS_BIN_DIR: where zenadm goes,
# by default /usr/local/bin, else ~/.local/bin, else the state dir, the first
# writable).
set -eu
# Where this script is published: install/stage.sh writes it in.
published='%s'
fail() { echo "install-container.sh: $*" >&2; exit 1; }
bin="${ZENTHROS_BIN_DIR:-}"
while [ "$#" -gt 0 ]; do
  arg="$1"
  shift
  case "${arg}" in
    --*=*)
      value="${arg#*=}"
      arg="${arg%%%%=*}"
      ;;
    --install-base|--artifact-urls|--sha256sums|--bin-dir)
      [ "$#" -gt 0 ] || fail "${arg} needs a value"
      value="$1"
      shift
      ;;
    *) fail "unknown argument ${arg}; the join's flags go to zenadm join" ;;
  esac
  case "${arg}" in
    --install-base) ZENTHROS_INSTALL_BASE="${value}" ;;
    --artifact-urls) ZENTHROS_ARTIFACT_URLS="${value}" ;;
    --sha256sums) ZENTHROS_SHA256SUMS_SHA256="${value#sha256:}" ;;
    --bin-dir) bin="${value}" ;;
    *) fail "unknown flag ${arg}; the join's flags go to zenadm join" ;;
  esac
done
ZENTHROS_INSTALL_BASE="${ZENTHROS_INSTALL_BASE:-${published}}"
[ -n "${ZENTHROS_INSTALL_BASE}${ZENTHROS_ARTIFACT_URLS:-}" ] ||
  fail "no install base: pass --install-base, or use the install-container.sh your hub publishes"
state="${ZENTHROS_STATE_DIR:-/tmp/zenthros}"
if [ -z "${bin}" ]; then
  for dir in /usr/local/bin "${HOME:-/nonexistent}/.local/bin" "${state}/bin"; do
    if mkdir -p "${dir}" 2>/dev/null && [ -w "${dir}" ]; then
      bin="${dir}"
      break
    fi
  done
fi
[ -n "${bin}" ] || fail "no writable directory for zenadm; pass --bin-dir"
mkdir -p "${bin}"
zenadm="${bin}/zenadm"
if [ -e "${zenadm}" ] && ! grep -qx '` + containerZenadmMark + `' "${zenadm}"; then
  fail "${zenadm} is not one install-container.sh wrote; pass --bin-dir"
fi
q() { printf "'%%s'" "$(printf '%%s' "$1" | sed "s/'/'\\\\''/g")"; }
# write_zenadm writes zenadm, pinned to SHA256SUMS digest $1, as zenadm.new.
write_zenadm() {
  {
    printf '#!/bin/sh\n%%s\n' '` + containerZenadmMark + `'
    printf 'ZENTHROS_INSTALL_BASE=%%s\n' "$(q "${ZENTHROS_INSTALL_BASE}")"
    printf 'ZENTHROS_ARTIFACT_URLS=%%s\n' "$(q "${ZENTHROS_ARTIFACT_URLS:-}")"
    printf 'ZENTHROS_SHA256SUMS_SHA256=%%s\n' "$(q "$1")"
    if [ -n "${ZENTHROS_STATE_DIR:-}" ]; then
      printf 'ZENTHROS_STATE_DIR=%%s\nexport ZENTHROS_STATE_DIR\n' "$(q "${ZENTHROS_STATE_DIR}")"
    fi
    cat <<'ZENTHROS_ZENADM'
`

// installerTail pins zenadm to the SHA256SUMS the agent was checked
// against and installs it.
const installerTail = `ZENTHROS_ZENADM
  } > "${zenadm}.new"
  chmod 0755 "${zenadm}.new"
}
write_zenadm "${ZENTHROS_SHA256SUMS_SHA256:-}"
pin="$(sh "${zenadm}.new" --fetch-only)" || { rm -f "${zenadm}.new"; exit 1; }
write_zenadm "${pin}"
mv -f "${zenadm}.new" "${zenadm}"
echo "OK  the agent, checked against SHA256SUMS from ${ZENTHROS_INSTALL_BASE}" >&2
echo "OK  ${zenadm}" >&2
case ":${PATH}:" in
  *":${bin}:"*) ;;
  *) echo "${bin} is not on PATH: run export PATH=\"${bin}:\$PATH\" first" >&2 ;;
esac
echo "Next: paste your one-time 'zenadm join ...' command." >&2
`

// zenadmBody is the zenadm the installer writes, after the download
// settings: join verifies the agent again against the pinned SHA256SUMS
// (containerboot.Fetch) and attaches the container. A provider's own
// variable adds its job grace when --job-grace is not given. --fetch-only is
// the installer's download: the one place that trusts the SHA256SUMS it
// gets when nothing pins it, and prints its digest.
const zenadmBody = `# zenadm in a container, written by install-container.sh. zenadm join
# attaches the container to Zenthros: zenthros-agent attach, with zenadm
# join's flags. zenthros-agent attach --stop ends it.
fetch_only=
case "${1:-}" in
  join) shift ;;
  --fetch-only) fetch_only=1 ;;
  *) echo "usage: zenadm join HUB --token zt1_... [...]" >&2; exit 2 ;;
esac
grace=
for arg in "$@"; do
  case "${arg}" in --job-grace|--job-grace=*) grace=given ;; esac
done
`

// Script is install-container.sh as published at base: the line
// install/stage.sh rewrites. With no base, the script needs --install-base.
func Script(base string) string {
	var b strings.Builder
	fmt.Fprintf(&b, installerHead, strings.TrimRight(base, "/"))
	b.WriteString(zenadmBody)
	// Each container provider's job grace, found by the variable it sets in
	// its containers.
	b.WriteString("if [ -z \"${grace}\" ]; then\n")
	for i, h := range containerhosts.All() {
		keyword := "elif"
		if i == 0 {
			keyword = "if"
		}
		fmt.Fprintf(&b, "  %s [ -n \"${%s:-}\" ]; then set -- \"$@\" --job-grace %s\n", keyword, h.IDEnv, h.JobGrace)
	}
	b.WriteString("  fi\nfi\nset -- attach \"$@\"\nzenthros_trust_sums=\n[ -z \"${fetch_only}\" ] || zenthros_trust_sums=1\n")
	b.WriteString(containerboot.Fetch)
	b.WriteString("if [ -n \"${fetch_only}\" ]; then\n  [ \"${agent}\" = \"${baked}\" ] || sum \"${dir}/SHA256SUMS\"\n  exit 0\nfi\n# The agent fetches uv through the same pins to complete the container's\n# Python (ZENTHROS_TOOLCHAINS): they go with it.\nexport ZENTHROS_INSTALL_BASE ZENTHROS_ARTIFACT_URLS ZENTHROS_SHA256SUMS_SHA256\nexec \"${agent}\" \"$@\"\n")
	b.WriteString(installerTail)
	return b.String()
}
